#!/usr/bin/env node
/**
 * Generate the inline hole previews in web/game.html.
 *
 * Each aerial template in web/img/holes/ is reduced to a 5x7 grid of RGB
 * values -- 105 bytes, 140 base64 characters -- and the whole set is written
 * into game.html as a literal. The game paints that grid, smoothly upscaled,
 * the instant a hole opens, so the field shows a soft version of the hole you
 * are actually on rather than a bare background while the real 20-80KB image
 * downloads. Measured before this existed: 0.6-1.5s of bare field at the start
 * of every round, tracking the download almost 1:1.
 *
 * It is inlined rather than served as its own file because the whole set is
 * under 3KB -- smaller than the request that would fetch it -- and because a
 * file under web/js would have to be kept in step with the cache-buster.
 *
 * Run after adding or recutting a template:  node scripts/gen-hole-previews.js
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const W = 5, H = 7;                       // 640x853 art is almost exactly 3:4
const HOLES_DIR = path.join(__dirname, '..', 'web', 'img', 'holes');
const GAME = path.join(__dirname, '..', 'web', 'game.html');
const START = '    // >>> hole previews — generated by scripts/gen-hole-previews.js, do not edit';
const END = '    // <<< hole previews';

(async () => {
  const names = fs.readdirSync(HOLES_DIR).filter((f) => f.endsWith('.webp'))
    .map((f) => f.replace(/\.webp$/, '')).sort();
  if (!names.length) { console.error('No templates in ' + HOLES_DIR); process.exit(1); }

  const rows = [];
  for (const name of names) {
    const raw = await sharp(path.join(HOLES_DIR, name + '.webp'))
      .resize(W, H, { fit: 'fill' }).removeAlpha().raw().toBuffer();
    rows.push("      '" + name + "': '" + raw.toString('base64') + "'");
  }

  const block = [
    START,
    '    var PREVIEW_W = ' + W + ', PREVIEW_H = ' + H + ';',
    '    var HOLE_PREVIEW = {',
    rows.join(',\n'),
    '    };',
    END,
  ].join('\n');

  const html = fs.readFileSync(GAME, 'utf8');
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a === -1 || b === -1) { console.error('Markers not found in web/game.html'); process.exit(1); }
  const next = html.slice(0, a) + block + html.slice(b + END.length);
  fs.writeFileSync(GAME, next);

  // The game's own HOLE_ART list has to name exactly these, or a hole draws
  // with no preview (or a preview nothing ever asks for).
  const listed = (next.match(/var HOLE_ART = \[([\s\S]*?)\]/) || [])[1] || '';
  const inGame = (listed.match(/'[a-z-]+'/g) || []).map((s) => s.slice(1, -1)).sort();
  const missing = inGame.filter((n) => !names.includes(n));
  const extra = names.filter((n) => !inGame.includes(n));
  if (missing.length) console.warn('WARNING: HOLE_ART names with no template: ' + missing.join(', '));
  if (extra.length) console.warn('WARNING: templates not in HOLE_ART: ' + extra.join(', '));

  const bytes = Buffer.byteLength(block, 'utf8');
  console.log(names.length + ' previews at ' + W + 'x' + H + ' — ' + (bytes / 1024).toFixed(1) + 'KB inlined');
})();
